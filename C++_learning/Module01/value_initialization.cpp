/*
তিন ধরনের Initialization আছে c++ e
1. Copy Initialization              -----> int x = 10;
2. Direct Initialization            -----> int x(10);
3. Brace / Uniform Initialization   -----> int x {10};

আগে আমরা যেভাবে int val1 = 10; বা int val1(10); লিখতাম, int val1 {10}; ঠিক একই কাজ করে—অর্থাৎ val1 ভ্যারিয়েবলের ভেতর 10 স্টোর করে।

এভাবে ডিক্লেয়ার করলে কি কোনো স্পেশাল সুবিধা (বা "ছাড়") আছে?
আসলে এভাবে লিখলে কম্পাইলার আপনাকে "ছাড়" দেয় না, বরং কড়াকড়ি আরোপ করে—যা প্রোগ্রামারদের জন্য বিশাল বড় একটি সুবিধা! 
এর প্রধান ৩টি স্পেশাল বৈশিষ্ট্য নিচে দেওয়া হলো:

১. ডাটা লস বা Narrowing Conversion রোধ করে (সবচেয়ে বড় সুবিধা)
সাধারণ সমান চিহ্ন (=) দিয়ে ভ্যারিয়েবল ডিক্লেয়ার করলে ডাটা লস হওয়ার ঝুঁকি থাকে, কিন্তু {} ব্যবহার করলে কম্পাইলার সাথে সাথে এরর (Error) ধরে ফেলে।

Example:
int a = 4.5;  // এটি কাজ করবে! কিন্তু .5 কেটে গিয়ে a এর মান হবে শুধু 4 (ডাটা লস হলো)।
int b {4.5};  // কম্পাইলার সাথে সাথে Error দেবে! কারণ পূর্ণসংখ্যায় (int) দশমিক রাখা সম্ভব নয়।
এভাবে অজান্তেই প্রোগ্রামে বড় ধরনের বাগ (Bug) তৈরি হওয়া থেকে {} আপনাকে বাঁচিয়ে দেয়।

২. ডিফল্ট ভ্যালু বা Zero Initialization (গার্বেজ ভ্যালু থেকে মুক্তি)
C++ এ সাধারণভাবে ভ্যারিয়েবল ডিক্লেয়ার করে কোনো মান না দিলে তার ভেতর আবোল-তাবোল সংখ্যা (Garbage Value) বসে থাকে। 
কিন্তু খালি {} দিলে ভ্যারিয়েবলটি নিজে থেকেই 0 (শূন্য) হয়ে যায়।

Example:
int x;     // এর ভেতর যেকোনো গার্বেজ ভ্যালু থাকতে পারে (যেমন: -858993460)
int y {};  // এর মান স্বয়ংক্রিয়ভাবে 0 সেট হয়ে যাবে!

৩. সব জায়গায় একই নিয়ম (Uniformity)
C++ এ সাধারণ ভ্যারিয়েবল, অ্যারে (Array), স্ট্রাকচার (Struct) বা ক্লাসের অবজেক্ট—একেকটাতে মান বসানোর নিয়ম আগে একেক রকম ছিল। 
{} আসার পর সব জায়গায় একই স্টাইলে ভ্যালু ইনিশিয়ালাইজ করা যায়:

Example:
int num {10};                  // সাধারণ ভ্যারিয়েবল
int arr[3] {1, 2, 3};          // অ্যারে (সমান চিহ্ন দেওয়ারও দরকার নেই)
std::string name {"Rahim"};    // স্ট্রিং বা অবজেক্ট

*/


